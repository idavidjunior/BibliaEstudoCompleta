import sqlite3, os
con = sqlite3.connect(os.path.join(os.path.dirname(__file__), "..", "assets", "databases", "biblia_estudo.db"))
print("user_version:", con.execute("PRAGMA user_version").fetchone()[0])
print("total versos:", con.execute("SELECT COUNT(*) FROM verses").fetchone()[0])
print("por traducao:", con.execute("SELECT translation_id, COUNT(*) FROM verses GROUP BY translation_id").fetchall())
print("schema verses:")
print(con.execute("SELECT sql FROM sqlite_master WHERE name='verses'").fetchone()[0])
print()
print("traducoes:", con.execute("SELECT * FROM translations").fetchall())
